returns text language sql security definer set search_path = ''
as $$ select public.com_cast_site_vote(p_commune, p_question, p_score, p_voter_hash) $$;
create or replace function public.site_vote_summary(p_commune text)
returns table (question text, votes bigint, average numeric) language sql stable security definer set search_path = ''
as $$ select * from public.com_site_vote_summary(p_commune) $$;

