-- Council as the card reads it (permanent): same columns as the former officeholders table.
create view public.com_v_officeholders with (security_invoker = true) as
select m.id, i.code as commune_code, s.role, p.last_name, p.first_name, m.start_date as mandate_start,
       m.function_start, m.end_date as mandate_end, m.source_id, s.rank, m.term_id, m.verified, m.source_url, p.sex
from public.mandates m
join public.seats s on s.id = m.seat_id
join public.bodies b on b.id = s.body_id and b.kind = 'conseil_municipal'
join public.institutions i on i.id = b.institution_id and i.kind = 'commune'
join public.persons p on p.id = m.person_id;

-- Check the backfill before dropping the old table: same rows, same values. Sex is the one expected change:
-- past-mayor rows (history file) had none and now share the person's RNE value (18 rows on 3 Nov 2026).
do $$
declare n_old bigint; n_new bigint; n_diff bigint; n_sex bigint;
begin
  select count(*) into n_old from public.officeholders;
  select count(*) into n_new from public.com_v_officeholders;
  select count(*) into n_diff from (
    (select id, commune_code, role, last_name, first_name, mandate_start, function_start, mandate_end, source_id,
            rank, term_id, verified, source_url from public.officeholders
     except select id, commune_code, role, last_name, first_name, mandate_start, function_start, mandate_end, source_id,
                   rank, term_id, verified, source_url from public.com_v_officeholders)
    union all
    (select id, commune_code, role, last_name, first_name, mandate_start, function_start, mandate_end, source_id,
            rank, term_id, verified, source_url from public.com_v_officeholders
     except select id, commune_code, role, last_name, first_name, mandate_start, function_start, mandate_end, source_id,
                   rank, term_id, verified, source_url from public.officeholders)) d;
  select count(*) into n_sex from public.officeholders o join public.com_v_officeholders v using (id)
  where o.sex is not null and o.sex is distinct from v.sex;
  if n_old <> n_new or n_diff <> 0 or n_sex <> 0 then
    raise exception 'officeholders backfill mismatch: old %, new %, differing rows %, sex changed %', n_old, n_new, n_diff, n_sex;
  end if;
  if (select count(*) from public.institutions) <> 34 or (select count(*) from public.bodies) <> 34 then
    raise exception 'expected 34 institutions and 34 bodies';
  end if;
end $$;

