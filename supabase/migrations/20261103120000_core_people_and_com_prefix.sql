-- ============================================================ 4. Votes: functions under the new names
create function public.com_cast_site_vote(p_commune text, p_question text, p_score int, p_voter_hash text)
returns text
language plpgsql security definer set search_path = ''
as $$
begin
  if exists (select 1 from public.com_site_votes
             where voter_hash = p_voter_hash and commune_code = p_commune and question = p_question
               and created_at > now() - interval '30 days') then
    return 'already_voted';
  end if;
  if (select count(*) from public.com_site_votes
      where voter_hash = p_voter_hash and created_at > now() - interval '1 day') >= 40 then
    return 'rate_limited';
  end if;
  insert into public.com_site_votes (commune_code, question, score, voter_hash)
  values (p_commune, p_question, p_score, p_voter_hash);
  return 'ok';
end $$;
revoke execute on function public.com_cast_site_vote(text, text, int, text) from public, anon, authenticated;
grant execute on function public.com_cast_site_vote(text, text, int, text) to service_role;

create function public.com_site_vote_summary(p_commune text)
returns table (question text, votes bigint, average numeric)
language sql stable security definer set search_path = ''
as $$
  select v.question, count(*) as votes,
         case when count(*) >= 20 then round(avg(v.score), 1) end as average   -- hidden below 20 votes
  from public.com_site_votes v
  where v.commune_code = p_commune
  group by v.question
$$;
revoke execute on function public.com_site_vote_summary(text) from public;
grant execute on function public.com_site_vote_summary(text) to anon, authenticated;

