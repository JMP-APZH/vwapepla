-- Foundation for parallel work (B1 communes · B2 parlementaires · B3 CTM · B4 Préfet).
-- 1. Generic core model for people and mandates: institutions → bodies → seats ← mandates → persons.
-- 2. Commune tables renamed with the com_ prefix.
-- 3. Compatibility: views with the old names + old RPC names as wrappers, so the app built from `main`
--    (vwapepla.org) keeps working on this shared database. Dropped by a later migration after the next release.
-- Runs in one transaction: any failed check below rolls everything back.

-- ============================================================ 1. Core tables (shared, no prefix)
create table public.institutions (
  id    text primary key,                         -- 'commune-97209', 'assemblee-nationale', 'senat', 'ctm', 'prefecture-972'
  kind  text not null check (kind in ('commune', 'assemblee_nationale', 'senat', 'ctm', 'prefecture')),
  name  text not null,
  code  text                                      -- INSEE or SIREN code when there is one
);

create table public.bodies (
  id              text primary key,               -- 'commune-97209-cm'
  institution_id  text not null references public.institutions(id),
  kind            text not null,                  -- 'conseil_municipal', 'assemblee', 'conseil_executif', ...
  name            text not null
);

create table public.seats (
  id            text primary key,                 -- 'commune-97209-cm:maire', ':adjoint-1', ':conseiller'
  body_id       text not null references public.bodies(id),
  role          text not null,                    -- 'maire', 'adjoint', 'conseiller', 'depute', 'prefet', ...
  rank          smallint,                         -- order when it matters (1er adjoint = 1)
  label_fr      text not null,
  constituency  text,                             -- e.g. deputies' circonscription
  unique nulls not distinct (body_id, role, rank)
);

-- Only what the cards need: no birth date, occupation or nationality (data minimisation).
create table public.persons (
  id          text primary key,                   -- stable key built by the domain pipeline, e.g. 'com-97209:NOM:Prénom'
  last_name   text not null,
  first_name  text not null,
  sex         text check (sex in ('F', 'M'))       -- only to write titles correctly ("1re adjointe")
);

-- Terms: existing municipal terms; other bodies add theirs (body_kind).
-- first_full_year / last_full_year = budget years in office (communes).
alter table public.terms add column body_kind text not null default 'conseil_municipal';
alter table public.terms alter column body_kind drop default;

create table public.mandates (
  id              bigint generated by default as identity primary key,
  person_id       text not null references public.persons(id),
  seat_id         text not null references public.seats(id),
  start_date      date not null,                  -- start of the mandate
  function_start  date,                           -- start of the function, if later (e.g. mayor elected by the council)
  end_date        date,                           -- null = current
  acquired        text not null check (acquired in ('direct_election', 'indirect_election', 'appointment')),
  term_id         text references public.terms(id),
  verified        boolean not null default true,  -- history rows: reviewed by JM
  source_id       text not null references public.sources(id),
  source_url      text,                           -- page proving the fact (history rows)
  unique (person_id, seat_id, start_date)
);
create index on public.mandates (seat_id);

alter table public.sources add column domain text not null default 'communes';
alter table public.sources alter column domain drop default;

alter table public.media add column institution_id text references public.institutions(id);
alter table public.media add column person_id text references public.persons(id);
alter table public.media alter column commune_code drop not null;

do $$
declare t text;
begin
  foreach t in array array['institutions', 'bodies', 'seats', 'persons', 'mandates'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "public read" on public.%I for select to anon, authenticated using (true)', t);
    execute format('revoke insert, update, delete, truncate on public.%I from anon, authenticated', t);
  end loop;
end $$;

-- ============================================================ 2. Backfill from communes + officeholders
insert into public.institutions (id, kind, name, code)
select 'commune-' || code, 'commune', name, code from public.communes;

insert into public.bodies (id, institution_id, kind, name)
select 'commune-' || code || '-cm', 'commune-' || code, 'conseil_municipal', 'Conseil municipal' from public.communes;

insert into public.seats (id, body_id, role, rank, label_fr)
select distinct
  'commune-' || commune_code || '-cm:' || role || coalesce('-' || rank, ''),
  'commune-' || commune_code || '-cm', role, rank,
  case role when 'maire' then 'Maire' when 'adjoint' then 'Adjoint au maire n° ' || rank else 'Conseiller municipal' end
from public.officeholders;

insert into public.persons (id, last_name, first_name, sex)
select distinct on (commune_code, last_name, first_name)
  'com-' || commune_code || ':' || last_name || ':' || first_name, last_name, first_name, sex
from public.officeholders
order by commune_code, last_name, first_name, sex nulls last;

insert into public.mandates (id, person_id, seat_id, start_date, function_start, end_date, acquired, term_id,
                             verified, source_id, source_url)
overriding system value
select id, 'com-' || commune_code || ':' || last_name || ':' || first_name,
       'commune-' || commune_code || '-cm:' || role || coalesce('-' || rank, ''),
       mandate_start, function_start, mandate_end,
       case role when 'conseiller' then 'direct_election' else 'indirect_election' end,
       term_id, verified, source_id, source_url
from public.officeholders;
select setval(pg_get_serial_sequence('public.mandates', 'id'), (select max(id) from public.mandates));

update public.media m set institution_id = 'commune-' || m.commune_code,
  person_id = case when m.kind = 'mayor_portrait' then (
    select o.person_id from public.mandates o join public.seats s on s.id = o.seat_id
    where s.body_id = 'commune-' || m.commune_code || '-cm' and s.role = 'maire' and o.end_date is null
    order by o.start_date desc limit 1) end;

